"""Build the small saved EPANET example used by the dashboard's demo mode (data/sample/).

Everything in the sample comes from the real pipeline: EPANET time series and scenario specs of a few TEST-split
scenarios, plus the stored forecasts of the trained random forest and GRU for those scenarios (out-of-sample), and the
real model-comparison table. Nothing is invented. Run it once after training (Phases 2-4):

    python scripts/build_demo_sample.py
"""
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

import numpy as np  # noqa: E402
import pandas as pd  # noqa: E402

from src.baseline_models import PersistenceBaseline, RandomForestBaseline  # noqa: E402
from src.dataset_builder import load_split  # noqa: E402
from src.utils import load_config, resolve_path  # noqa: E402

PER_FAMILY = {"normal": 2, "high_source_pressure": 2, "valve_misconfiguration": 2, "high_demand_stress": 1,
              "reduced_supply": 1, "pump_degradation": 1, "partial_blockage": 1, "small_leak": 2, "burst_leak": 1}
SAMPLE = Path("data/sample")


def main() -> int:
    cfg = load_config()
    P = {k: resolve_path(v) for k, v in cfg["paths"].items()}
    for need in ("raw_timeseries", "scenario_specs", "scenario_metadata", "test_npz", "feature_names", "random_forest",
                 "model_comparison"):
        if not Path(P[need]).exists():
            print(f"ERROR: {P[need]} not found. Run Phases 2-4 first.", file=sys.stderr)
            return 1
    test = load_split(P["test_npz"])
    meta = pd.read_csv(P["scenario_metadata"])
    test_ids = set(map(str, np.unique(test["meta_scenario_id"])))
    chosen = []
    for fam, n in PER_FAMILY.items():
        ids = sorted(i for i in meta.loc[meta["scenario_type"] == fam, "scenario_id"] if i in test_ids)
        chosen += ids[:n]
    print("sample scenarios (all from the TEST split):", chosen)

    out = resolve_path(SAMPLE)
    out.mkdir(parents=True, exist_ok=True)
    raw = pd.read_csv(P["raw_timeseries"])
    raw[raw["scenario_id"].isin(chosen)].to_csv(out / "sample_timeseries.csv", index=False)
    meta[meta["scenario_id"].isin(chosen)].to_csv(out / "sample_scenario_metadata.csv", index=False)
    with open(P["scenario_specs"], encoding="utf-8") as src, open(out / "sample_scenario_specs.jsonl", "w", encoding="utf-8") as dst:
        for line in src:
            if json.loads(line)["scenario_id"] in chosen:
                dst.write(line)
    pd.read_csv(P["model_comparison"]).to_csv(out / "sample_model_comparison.csv", index=False)

    feats = json.loads(Path(P["feature_names"]).read_text(encoding="utf-8"))["input_features"]
    nodes = list(cfg["ml"]["target_nodes"])
    keep = np.isin(test["meta_scenario_id"], chosen)
    x = test["X_raw"][keep]
    models = {"persistence": PersistenceBaseline(feats, nodes), "random_forest": RandomForestBaseline.load(P["random_forest"])}
    try:
        from src.gru_model import GRUPredictor
        models["gru"] = GRUPredictor.from_checkpoint(P["gru_checkpoint"])
    except Exception as exc:                                                   # noqa: BLE001
        print(f"note: GRU not stored in the sample ({exc})")
    rows = []
    for name, m in models.items():
        fc = m.predict(x)
        df = pd.DataFrame(fc, columns=[f"{n}_pressure" for n in nodes])
        df.insert(0, "model", name)
        df.insert(0, "step", test["meta_end_step"][keep].astype(int))
        df.insert(0, "scenario_id", test["meta_scenario_id"][keep].astype(str))
        rows.append(df)
    pd.concat(rows).to_csv(out / "sample_forecasts.csv", index=False, float_format="%.5f")
    (out / "README.md").write_text(
        "# Demo sample\n\nSynthetic EPANET simulation example. Generated by `scripts/build_demo_sample.py` from the real "
        "pipeline: EPANET time series and scenario specs of a few TEST-split scenarios, stored (pre-computed) forecasts "
        "of the trained models for those scenarios, and the real model-comparison table. Not real utility data.\n",
        encoding="utf-8")
    for f in sorted(out.iterdir()):
        print(f"  {f.name:34s}{f.stat().st_size / 1024:8.0f} KB")
    return 0


if __name__ == "__main__":
    sys.exit(main())
